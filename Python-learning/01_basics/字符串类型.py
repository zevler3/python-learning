"""
字符串类型：连续的字符序列，可以表示计算机所能识别的一切字符

索引：对某个字符串的检索

切片：对字符串某个子串或区间的检索

字符串的界定符：单引号、双引号、三引号

转义字符:
换符号(\n)
水平制位表(\t)
双引号(\")
单引号(\')
一个反斜杠(\\)

原字符：使转义字符失效的字符，r或R

"""

#字符串类型的使用(单引号的使用)
city='临江市'
address='临江市百花大道'
print(city)
print(address)

#转义字符的使用
print('赞美')
print('愚者')
print('------------------')
print('赞美\n愚者')

print('赞美\t愚者')#一个汉字占两格
print('赞美赞美\t愚者')

print('a\tb') #一个制表位有八个字符
print('aa\tb')
print('aaa\tb')

print('\'赞美愚者\'')

#原字符地使用
print(r'\'赞美愚者\'')

#字符串的索引与切片的使用
z='周明瑞'
print(z[0],z[2])
print(z[0])
a='赞美愚者'
print(a[1:3]) #从1开始到3结束，不包含3，正向递增
print(a[-3:-1]) #反向递增
print(a[:3]) #默认从0开始，3结束
print(a[3:]) #默认切到字符串结尾，从3开始

#常用的字符串操作
e='赞美'
b='愚者'

print(e+b)  #连接

print(e*2)  #复制
print(2*e)

print("愚者"in'愚者愚者') #判断是否为子串
print("阿蒙"in'赞美愚者')